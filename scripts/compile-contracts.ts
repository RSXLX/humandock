import { createRequire } from 'node:module';
import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import solc from 'solc';

const require = createRequire(import.meta.url);
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export interface ContractArtifact { contractName: string; sourceName: string; compilerVersion: string; evmVersion: 'paris'; abi: readonly unknown[]; bytecode: `0x${string}`; deployedBytecode: `0x${string}` }

/** No RPC or keys are used. Imports resolve from the pinned local npm installation. */
export async function compileContracts(writeArtifacts = true): Promise<Record<string, ContractArtifact>> {
  const sources: Record<string, { content: string }> = {};
  for (const file of (await readdir(join(root, 'contracts'))).filter((name) => name.endsWith('.sol')).sort()) {
    sources[`contracts/${file}`] = { content: await readFile(join(root, 'contracts', file), 'utf8') };
  }
  const input = {
    language: 'Solidity', sources,
    settings: {
      optimizer: { enabled: true, runs: 200 }, viaIR: true, evmVersion: 'paris',
      outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object'] } },
    },
  };
  // solc's import callback is synchronous by design.
  const { readFileSync } = await import('node:fs');
  const output = JSON.parse(solc.compile(JSON.stringify(input), { import: (path: string) => {
    if (!path.startsWith('@openzeppelin/contracts/')) return { error: 'Only pinned OpenZeppelin imports are allowed' };
    try { return { contents: readFileSync(require.resolve(path), 'utf8') }; }
    catch { return { error: `Unable to resolve ${path}` }; }
  } }));
  const errors = (output.errors ?? []).filter((error: { severity: string }) => error.severity === 'error');
  if (errors.length) throw new Error(errors.map((error: { formattedMessage: string }) => error.formattedMessage).join('\n'));
  const artifacts: Record<string, ContractArtifact> = {};
  for (const [sourceName, contracts] of Object.entries(output.contracts ?? {})) {
    if (!sourceName.startsWith('contracts/')) continue;
    for (const [contractName, raw] of Object.entries(contracts as Record<string, any>)) {
      if (!raw.evm.bytecode.object) continue;
      if (raw.evm.deployedBytecode.object.length / 2 > 24_576) throw new Error(`${contractName} exceeds EIP-170 deployed size limit`);
      artifacts[contractName] = { contractName, sourceName, compilerVersion: solc.version(), evmVersion: 'paris', abi: raw.abi, bytecode: `0x${raw.evm.bytecode.object}`, deployedBytecode: `0x${raw.evm.deployedBytecode.object}` };
    }
  }
  if (writeArtifacts) {
    const directory = join(root, 'contracts/artifacts');
    await mkdir(directory, { recursive: true });
    for (const artifact of Object.values(artifacts)) await writeFile(join(directory, `${artifact.contractName}.json`), `${JSON.stringify(artifact, null, 2)}\n`);
    await mkdir(join(root, 'packages/me/src'), { recursive: true });
    const generated = '// Generated by npm run contracts:compile. Do not edit. Target: paris.\n' + Object.values(artifacts).map((a) => `export const ${a.contractName[0].toLowerCase()}${a.contractName.slice(1)}Abi = ${JSON.stringify(a.abi, null, 2)} as const;\n`).join('\n');
    await writeFile(join(root, 'packages/me/src/generated-abis.ts'), generated);
  }
  return artifacts;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const artifacts = await compileContracts();
  console.log(JSON.stringify({ compiler: solc.version(), evmVersion: 'paris', contracts: Object.values(artifacts).map((a) => ({ name: a.contractName, runtimeBytes: (a.deployedBytecode.length - 2) / 2 })), deployed: false }, null, 2));
}
